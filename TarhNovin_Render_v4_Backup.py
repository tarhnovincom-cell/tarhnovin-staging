def _validate_environment():
    if os.environ.get('APP_ENV') != 'staging':
        raise SystemExit('Refusing to run: APP_ENV must be staging (fictional demo only).')
    if len(os.environ.get('SESSION_SECRET','')) < 32:
        raise SystemExit('Configure a private SESSION_SECRET >= 32 chars in Render.')
    if len(os.environ.get('STAGING_GATE_PASSWORD','')) < 16:
        raise SystemExit('Configure a private STAGING_GATE_PASSWORD >= 16 chars in Render.')
    if len(os.environ.get('ADMIN_PASSWORD','')) < 12:
        raise SystemExit('Configure a private ADMIN_PASSWORD >= 12 chars in Render.')
    os.environ.setdefault('STAGING_GATE_USERNAME','review')
    os.environ.setdefault('DATABASE_URL','sqlite:///./data/staging-preview.sqlite3')

def _unpack():
    root = Path(__file__).resolve().parent / '.tarhnovin_staging_runtime'
    root.mkdir(parents=True, exist_ok=True)
    archive_bytes = base64.b85decode(''.join(_ARCHIVE))
    with tarfile.open(fileobj=io.BytesIO(archive_bytes),mode='r:gz') as tar:
        for member in tar.getmembers():
            target=(root/member.name).resolve()
            if not target.is_relative_to(root.resolve()) or not member.isfile():
                raise SystemExit('Unexpected bundle member type or path')
            target.parent.mkdir(parents=True,exist_ok=True)
            with tar.extractfile(member) as source, open(target,'wb') as destination:
                while True:
                    b=source.read(65536)
                    if not b:break
                    destination.write(b)
    return root

def main():
    _validate_environment()
    root=_unpack()
    os.chdir(root)
    sys.path.insert(0,str(root))
    import runpy
    runpy.run_path(str(root/'bootstrap_preview.py'),run_name='__main__')
    import uvicorn
    port=int(os.environ.get('PORT','10000'))
    uvicorn.run('app.main:app',host='0.0.0.0',port=port,workers=1)

if __name__=='__main__':
    main()
